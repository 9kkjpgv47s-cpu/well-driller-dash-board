#!/usr/bin/env python3
"""Generate docs/design/perf/RESULTS.md from A/B/C JSONs."""
import json, sys, os

D = os.path.dirname(os.path.abspath(__file__))

def load(n):
    p = os.path.join(D, f"{n}.json")
    return json.load(open(p)) if os.path.exists(p) else None

A, B, C = load("A"), load("B"), load("C")
LAB = {"A": "A · pre-restyle (:3005)", "B": "B · pre-perf HEAD (:3001)", "C": "C · perf pass (:3001)"}
METRICS = [
    ("loadReadyMs", "load ready (ms)"),
    ("loadLongTaskMs", "load long-task (ms)"),
    ("refreshMs", "pan→refresh settle (ms)"),
    ("refreshWorkMs", "refreshMap work (ms)"),
    ("refreshCount", "pan→refresh calls"),
    ("wheelRefreshCount", "wheel 40× → refresh calls"),
    ("wheelRefreshWorkMs", "wheel → refreshMap work (ms)"),
    ("wheelLongTaskMs", "wheel long-task (ms)"),
    ("wheelMaxFrameGap", "wheel max frame gap (ms)"),
    ("wheelFramesGt50", "wheel frames >50ms"),
    ("zoomRefreshCount", "zoom step → refresh calls"),
    ("zoomSettleMs", "zoom step settle (ms)"),
    ("filterOffMs", "toggle off settle (ms)"),
    ("filterOnMs", "toggle on settle (ms)"),
    ("scrollMaxFrameGap", "page-scroll max gap (ms)"),
    ("scrollFramesGt50", "page-scroll frames >50ms"),
]

def fmt(v):
    if v is None: return "—"
    if isinstance(v, float): return f"{v:.1f}"
    return str(v)

def delta(b, c):
    if b is None or c is None or b == 0: return ""
    d = (c - b) / b * 100
    return f" ({'+' if d > 0 else ''}{d:.0f}%)"

out = ["# Well Viewer — perf results", "",
       "Harness: `apps/hub/scripts/design-baseline/perf.mjs` — Playwright, tiles/3rd-party aborted,",
       "fixed z15 view at lat 39.763 lon −86.399, seeded `Math.random` (subsample reproducible),",
       "3 runs per profile, medians. Profiles: desktop 1440×900 · ipad 820×1180 dpr2 cpu4× · phone 390×844 dpr3 cpu4×.",
       "", "**Labels:** A = pre-restyle baseline (:3005) · B = pre-perf HEAD (:3001) · C = perf pass (:3001).",
       "`refreshMap work` = summed wall time inside `refreshMap()` during the measured window;",
       "B has no work counter, so its proxy = `refreshMs` (1 synchronous call) / `wheelLongTaskMs` (40 calls).",
       ""]
for prof in ("desktop", "ipad", "phone"):
    out += [f"## {prof}", "",
            "| metric | A | B | C | C vs B |", "|---|---|---|---|---|"]
    for k, label in METRICS:
        va = (A or {}).get("profiles", {}).get(prof, {}).get("median", {}).get(k)
        vb = (B or {}).get("profiles", {}).get(prof, {}).get("median", {}).get(k)
        vc = (C or {}).get("profiles", {}).get(prof, {}).get("median", {}).get(k)
        if va is None and vb is None and vc is None:
            continue
        out.append(f"| {label} | {fmt(va)} | {fmt(vb)} | {fmt(vc)} |{delta(vb, vc)} |")
    out.append("")
out.append("_Generated by gen-results.py_")
open(os.path.join(D, "RESULTS.md"), "w").write("\n".join(out) + "\n")
print("wrote RESULTS.md")
